#!/bin/sh
set -eu

# LeopardOS 预装镜像组装（modern 布局，对齐安装器默认方案）
#   p0 ESP 64 MiB FAT32 -> /boot
#   p1 ext4 root         -> /
#   p2 ext4 /users       -> /users
#
# 默认 5 GiB（对齐官方内测推荐容量，可用 IMG_MIB 覆盖）。
# 只消费各组件 out/*.xbps；宿主机需要 mkfs.ext4（支持 -d）、sgdisk、mtools。
#
# 环境变量：IMG_MIB（默认 5120）、IMAGE（默认 XJ380.img）、VMDK

ROOT=$(cd "$(dirname "$0")" && pwd)
PROJ="$ROOT/../.."
XBP="$PROJ/leopard-xbps/out"
MANIFEST="$ROOT/../build/packages.conf"

IMAGE="${IMAGE:-$ROOT/XJ380.img}"
VMDK="${VMDK:-$ROOT/XJ380.vmdk}"
IMG_MIB="${IMG_MIB:-5120}"
STAGE="$ROOT/.stage"
REPO="$ROOT/.repo"
WORK="$ROOT/.work"
ESP_MIB=64

export PATH="$XBP:$PATH"

for tool in mkfs.ext4 mkfs.vfat sgdisk mcopy mmd qemu-img python3 xbps-rindex xbps-install; do
    command -v "$tool" >/dev/null 2>&1 || { echo "缺少工具: $tool" >&2; exit 1; }
done

rm -rf "$REPO" "$STAGE" "$WORK"
mkdir -p "$REPO" "$WORK"

# 1. 收包 + 本地仓库索引
PACKAGES=""
while read -r dir _script pkg; do
    case "$dir" in ''|'#'*) continue ;; esac
    find "$PROJ/$dir/out" -maxdepth 1 -name '*.xbps' -exec cp -t "$REPO" {} +
    PACKAGES="$PACKAGES $pkg"
done < "$MANIFEST"
xbps-rindex -a "$REPO"/*.xbps >/dev/null

# 2. 安装到 stage（xbps 包内容原样释放）
xbps-install -y -r "$STAGE" -R "$REPO" $PACKAGES >/dev/null
mkdir -p "$STAGE/system/config" "$STAGE/system/repo" "$STAGE/boot" "$STAGE/users" "$STAGE/config/xbps.d"
echo "repository=/system/repo" > "$STAGE/config/xbps.d/repo.conf"
cp "$REPO"/* "$STAGE/system/repo/"

# modern 的 /boot、/users 由 mountd 挂载；fstab 与安装器保持一致
cat > "$STAGE/system/config/fstab" <<'EOF'
# LeopardOS fstab — generated by assemble_image.sh (modern)
# <device> <mountpoint> [fstype]
/dev/sata0p0 /boot fatfs
/dev/sata0p2 /users ext4
EOF

# 3. 分区尺寸（root 30%，下限 512 MiB；其余给 /users）
TOTAL_SECTORS=$((IMG_MIB * 2048))
ESP_SECTORS=$((ESP_MIB * 2048))
FIRST=2048
LAST=$((TOTAL_SECTORS - 34))
REMAIN=$((LAST - (FIRST + ESP_SECTORS) + 1))
ROOT_SECTORS=$((REMAIN * 30 / 100))
[ "$ROOT_SECTORS" -ge $((512 * 2048)) ] || ROOT_SECTORS=$((512 * 2048))
ROOT_SECTORS=$((ROOT_SECTORS & ~2047))
[ "$ROOT_SECTORS" -lt "$REMAIN" ] || { echo "镜像太小，无法分出 root/users" >&2; exit 1; }
USERS_SECTORS=$((REMAIN - ROOT_SECTORS))
USERS_SECTORS=$((USERS_SECTORS & ~7))
ROOT_MIB=$((ROOT_SECTORS / 2048))
USERS_MIB=$((USERS_SECTORS / 2048))
ROOT_START=$((FIRST + ESP_SECTORS))
USERS_START=$((ROOT_START + ROOT_SECTORS))
USERS_END=$((USERS_START + USERS_SECTORS - 1))

echo ">>> 镜像布局: ${IMG_MIB} MiB = ESP ${ESP_MIB} MiB + root ${ROOT_MIB} MiB + users ${USERS_MIB} MiB"

# 4. 建裸盘 + GPT（先有 GUID，root.bin 需要）
rm -f "$IMAGE"
truncate -s "${IMG_MIB}M" "$IMAGE"
sgdisk "$IMAGE" -n "1:${FIRST}:$((FIRST + ESP_SECTORS - 1))" -t 1:ef00 -c 1:ESP \
    -n "2:${ROOT_START}:$((ROOT_START + ROOT_SECTORS - 1))" -t 2:8300 -c 2:root \
    -n "3:${USERS_START}:${USERS_END}" -t 3:8300 -c 3:users >/dev/null 2>&1

DISK_GUID=$(sgdisk -p "$IMAGE" 2>/dev/null | awk -F': ' '/Disk identifier \(GUID\)/{print $2; exit}')
ROOT_GUID=$(sgdisk -i 2 "$IMAGE" 2>/dev/null | awk -F': ' '/Partition unique GUID/{print $2; exit}')
ESP_GUID=$(sgdisk -i 1 "$IMAGE" 2>/dev/null | awk -F': ' '/Partition unique GUID/{print $2; exit}')
[ -n "$DISK_GUID" ] && [ -n "$ROOT_GUID" ] && [ -n "$ESP_GUID" ] || {
    echo "读取 GPT GUID 失败" >&2; exit 1;
}

# 5. root/users ext4（mkfs.ext4 -d 直接铺 stage 目录）
ROOT_UUID=$(uuidgen)
USERS_UUID=$(uuidgen)
mkdir -p "$WORK/empty"
echo ">>> 生成 ext4 root (${ROOT_MIB} MiB) ..."
mkfs.ext4 -q -F -O ^orphan_file -L LEOPARD -U "$ROOT_UUID" -d "$STAGE" "$WORK/root.img" "${ROOT_MIB}M"
echo ">>> 生成 ext4 users (${USERS_MIB} MiB) ..."
mkfs.ext4 -q -F -O ^orphan_file -L LP-USERS -U "$USERS_UUID" -d "$WORK/empty" "$WORK/users.img" "${USERS_MIB}M"

# 6. ESP：引导器 + 内核 + boot.conf + root.bin
echo ">>> 生成 ESP (${ESP_MIB} MiB) ..."
dd if=/dev/zero of="$WORK/esp.img" bs=1M count="$ESP_MIB" status=none
mkfs.vfat -F 32 -n LP-ESP "$WORK/esp.img" >/dev/null
mmd -i "$WORK/esp.img" ::/EFI ::/EFI/BOOT ::/EFI/XJ380 ::/system
mcopy -i "$WORK/esp.img" "$STAGE/EFI/BOOT/BOOTX64.EFI" ::/EFI/BOOT/BOOTX64.EFI
mcopy -i "$WORK/esp.img" "$STAGE/system/kernel.krl"      ::/system/kernel.krl
printf '# generated by assemble_image.sh\ninit=/system/leopard/leopard-rc.elf\n' > "$WORK/boot.conf"
mcopy -i "$WORK/esp.img" "$WORK/boot.conf" ::/system/boot.conf

python3 - "$STAGE/system/kernel.krl" "$WORK/root.bin" \
    "$DISK_GUID" "$ROOT_GUID" "$ESP_GUID" "$ROOT_UUID" <<'PY'
import struct, sys, uuid

kernel_path, out_path, disk_s, root_s, esp_s, ext4_s = sys.argv[1:7]

def crc32c(data):
    c = 0xffffffff
    for byte in data:
        c ^= byte
        for _ in range(8):
            c = (c >> 1) ^ ((0 - (c & 1)) & 0x82f63b78)
    return c ^ 0xffffffff

kernel = open(kernel_path, "rb").read()
binding = bytearray(96)
binding[0:8] = b"XJROOT01"
struct.pack_into("<I", binding, 8, 1)          # version 1 = ext4
struct.pack_into("<I", binding, 12, 96)        # fixed size
binding[16:32] = uuid.UUID(disk_s).bytes_le
binding[32:48] = uuid.UUID(root_s).bytes_le
binding[48:64] = uuid.UUID(esp_s).bytes_le
binding[64:80] = uuid.UUID(ext4_s).bytes
struct.pack_into("<Q", binding, 80, len(kernel))
struct.pack_into("<I", binding, 88, crc32c(kernel))
struct.pack_into("<I", binding, 92, crc32c(bytes(binding[0:92])))
open(out_path, "wb").write(binding)
print("root.bin: kernel=%d bytes crc=%08x" % (len(kernel), crc32c(kernel)))
PY
mcopy -i "$WORK/esp.img" "$WORK/root.bin" ::/EFI/XJ380/root.bin

# 7. 把三个分区镜像写回裸盘
dd if="$WORK/esp.img"   of="$IMAGE" bs=1M seek=1 conv=notrunc status=none
dd if="$WORK/root.img"  of="$IMAGE" bs=1M seek=$((1 + ESP_MIB)) conv=notrunc status=none
dd if="$WORK/users.img" of="$IMAGE" bs=1M seek=$((1 + ESP_MIB + ROOT_MIB)) conv=notrunc status=none

# 8. vmdk
rm -f "$VMDK"
qemu-img convert -f raw -O vmdk -o subformat=monolithicSparse "$IMAGE" "$VMDK"

rm -rf "$STAGE" "$REPO" "$WORK"
echo "镜像已生成: $IMAGE (${IMG_MIB} MiB, modern) -> $VMDK"
